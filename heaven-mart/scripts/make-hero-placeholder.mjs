/**
 * Hero placeholder plate generator.
 *
 * Run:  npm run placeholder
 *
 * The real hero photograph (a graded Heaven showroom shot) is not delivered
 * yet. This renders an HONEST stand-in: an atmospheric Heaven-Ink plate with
 * a warm brass light pool and a suggested floor horizon. It deliberately
 * depicts NO furniture, because inventing furniture the client does not sell
 * would be a lie in a brief that only allows touch-up of real photography.
 *
 * The hero consumes it through one constant (HERO_PHOTO in Hero.tsx), so the
 * real photo swaps in by changing that path and re-running `npm run photos`.
 *
 * Also emits the LQIP base64 that next/image uses for blurDataURL, so the
 * blur-up path is exercised now exactly as it will be with the real photo.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUT_DIR = join(ROOT, 'public', 'img')
const OUT_IMG = join(OUT_DIR, 'hero-room-placeholder.webp')
const OUT_TS = join(ROOT, 'src', 'content', 'hero-blur.generated.ts')

const W = 1920
const H = 1440

/* Heaven Ink palette (globals.css tokens) */
const INK = '#0c1312'
const INK_LIFT = '#16211f'
const BRASS = '#c8a96a'

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
  <defs>
    <linearGradient id="ground" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="${INK}"/>
      <stop offset="55%" stop-color="${INK_LIFT}"/>
      <stop offset="100%" stop-color="#080d0c"/>
    </linearGradient>
    <radialGradient id="keyPool" cx="34%" cy="30%" r="52%">
      <stop offset="0%" stop-color="${BRASS}" stop-opacity="0.30"/>
      <stop offset="45%" stop-color="${BRASS}" stop-opacity="0.10"/>
      <stop offset="100%" stop-color="${BRASS}" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="rimPool" cx="82%" cy="68%" r="46%">
      <stop offset="0%" stop-color="#bcd2e8" stop-opacity="0.10"/>
      <stop offset="100%" stop-color="#bcd2e8" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="floor" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#ffffff" stop-opacity="0.05"/>
      <stop offset="100%" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
    <radialGradient id="vignette" cx="50%" cy="45%" r="72%">
      <stop offset="60%" stop-color="#000000" stop-opacity="0"/>
      <stop offset="100%" stop-color="#000000" stop-opacity="0.55"/>
    </radialGradient>
  </defs>

  <rect width="${W}" height="${H}" fill="url(#ground)"/>
  <rect width="${W}" height="${H}" fill="url(#keyPool)"/>
  <rect width="${W}" height="${H}" fill="url(#rimPool)"/>

  <!-- the suggested floor: a soft horizon and its pooled light, no objects -->
  <rect y="${H * 0.62}" width="${W}" height="${H * 0.38}" fill="url(#floor)"/>
  <rect y="${H * 0.62}" width="${W}" height="1" fill="${BRASS}" opacity="0.16"/>
  <ellipse cx="${W * 0.38}" cy="${H * 0.66}" rx="${W * 0.30}" ry="${H * 0.05}"
           fill="${BRASS}" opacity="0.05"/>

  <rect width="${W}" height="${H}" fill="url(#vignette)"/>
</svg>`

await mkdir(OUT_DIR, { recursive: true })

const base = sharp(Buffer.from(svg))

/* q82 with effort 6: the plate is pure gradient, so it compresses to a few KB
   and stays smooth (banding is the only real risk in a dark gradient) */
await base.clone().webp({ quality: 82, effort: 6 }).toFile(OUT_IMG)

/* LQIP: next/image blurs this itself, so 16px wide is plenty */
const lqip = await base.clone().resize(16).webp({ quality: 55 }).toBuffer()
const dataUrl = `data:image/webp;base64,${lqip.toString('base64')}`

await writeFile(
  OUT_TS,
  `/* GENERATED by scripts/make-hero-placeholder.mjs. Do not edit by hand.\n` +
    `   Re-run: npm run placeholder */\n` +
    `export const heroBlurDataUrl =\n  '${dataUrl}'\n`,
  'utf8',
)

console.log(`wrote ${OUT_IMG} (${W}x${H})`)
console.log(`wrote ${OUT_TS} (lqip ${lqip.length} bytes)`)
